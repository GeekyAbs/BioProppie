"""Build static data for the Cloudflare Pages Function runtime.

Run after editing data/corpus.json:
    .venv/bin/python scripts/build-worker-data.py

The generated file is committed so Cloudflare Pages needs no build command.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from retrieval import STOPWORDS, HashingEmbedder, _chunk_document, tokenize  # noqa: E402

CORPUS = ROOT / "data" / "corpus.json"
OUTPUT = ROOT / "functions" / "data.generated.js"


def main() -> None:
    docs = json.loads(CORPUS.read_text())["documents"]
    embedder = HashingEmbedder()

    chunks = []
    for doc in docs:
        for chunk in _chunk_document(doc):
            chunks.append(
                {
                    "id": chunk["chunk_id"],
                    "docId": chunk["doc_id"],
                    "kind": chunk["kind"],
                    "text": chunk["text"],
                    "tokens": tokenize(chunk["text"]),
                    "type": doc.get("type", "paper"),
                    "title": doc.get("title", ""),
                    "date": doc.get("date", ""),
                    "display_date": doc.get("display_date", ""),
                    "journal": doc.get("journal", ""),
                    "url": doc.get("url"),
                    "live": bool(doc.get("live", False)),
                }
            )

    vectors = embedder.embed([chunk["text"] for chunk in chunks])
    df: Counter[str] = Counter()
    for chunk in chunks:
        df.update(set(chunk["tokens"]))
    avgdl = sum(len(chunk["tokens"]) for chunk in chunks) / max(len(chunks), 1)

    for chunk, vector in zip(chunks, vectors):
        chunk["vector"] = [round(float(value), 6) for value in vector]

    def js_json(value):
        return json.dumps(value, separators=(",", ":"), ensure_ascii=False).replace("</", "<\\/")

    output = f"""// Generated by scripts/build-worker-data.py — do not edit by hand.
export const VECTOR_DIMS = {embedder.dimensions};
export const STOPWORDS = {js_json(sorted(STOPWORDS))};
export const DOCUMENTS = {js_json(docs)};
export const CHUNKS = {js_json(chunks)};
export const DF = {js_json(dict(df))};
export const BM25_N = {len(chunks)};
export const AVGDL = {round(avgdl, 6)};
"""
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(output)
    print(f"wrote {OUTPUT} ({len(docs)} docs, {len(chunks)} chunks, {OUTPUT.stat().st_size / 1024:.0f} KB)")


if __name__ == "__main__":
    main()
